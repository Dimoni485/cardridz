import { useMemo, useState, type ReactNode } from "react";
import { Link } from "react-router-dom";
import { PageHeader } from "../components/ui";
import { useAuth } from "../auth";
import { ROLE_LABELS } from "../roles";

interface HelpSection {
  id: string;
  title: string;
  keywords: string;
  body: ReactNode;
}

export function HelpPage() {
  const { canEdit, isAdmin } = useAuth();
  const [query, setQuery] = useState("");
  const [active, setActive] = useState("start");

  const sections = useMemo(() => buildSections(canEdit, isAdmin), [canEdit, isAdmin]);

  const visible = useMemo(() => {
    const needle = query.trim().toLowerCase();
    if (!needle) return sections;
    return sections.filter((section) =>
      `${section.title} ${section.keywords}`.toLowerCase().includes(needle),
    );
  }, [query, sections]);

  function jump(id: string) {
    setActive(id);
    document
      .getElementById(`help-${id}`)
      ?.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  return (
    <div>
      <PageHeader
        title="Помощь"
        subtitle="Инструкция по работе с системой учёта картриджей и печатающей техники"
        actions={
          <button className="button print-hide" onClick={() => window.print()}>
            Печать
          </button>
        }
      />

      <div className="toolbar print-hide">
        <input
          className="input toolbar-search"
          placeholder="Поиск по инструкции: заправка, отчёт, списание…"
          value={query}
          onChange={(event) => setQuery(event.target.value)}
        />
        {query && (
          <button className="button" onClick={() => setQuery("")}>
            Сбросить
          </button>
        )}
        <span className="muted small">
          Найдено разделов: {visible.length} из {sections.length}
        </span>
      </div>

      <div className="help-layout">
        <nav className="card help-nav print-hide" aria-label="Оглавление">
          <div className="help-nav-title">Разделы</div>
          {visible.length === 0 && (
            <p className="muted small">Ничего не найдено — измените запрос.</p>
          )}
          {visible.map((section) => (
            <button
              key={section.id}
              type="button"
              className={`help-nav-link ${active === section.id ? "active" : ""}`}
              onClick={() => jump(section.id)}
            >
              {section.title}
            </button>
          ))}
        </nav>

        <div className="help-body">
          {visible.length === 0 && (
            <div className="card">
              <p className="empty-text">
                По запросу «{query}» ничего не найдено. Попробуйте другое слово или
                сбросьте поиск.
              </p>
            </div>
          )}

          {visible.map((section) => (
            <section
              key={section.id}
              id={`help-${section.id}`}
              className="card help-section"
            >
              <h2>{section.title}</h2>
              {section.body}
            </section>
          ))}
        </div>
      </div>
    </div>
  );
}

